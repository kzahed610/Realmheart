#!/usr/bin/env python3
"""Exercise the real realmheart-wallpaper-renderer inside an isolated Hyprland.

The unit tests use a scripted fixture renderer, so they cannot prove that the
native renderer still renders after a refactor. This harness starts a private
nested Hyprland with one headless output, runs the real renderer against its
Wayland socket, speaks the stdio protocol, and captures the output.

Usage:
  python3 tools/display-tests/renderer_smoke.py [--renderer PATH] [--keep]
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_NAME = "REALMHEART-TEST"
OUTPUT_SIZE = "1920x1080@60"


class HarnessError(RuntimeError):
    pass


STALE_SESSION_PREFIX = "/tmp/realmheart-renderer-smoke-"


def hyprland_processes() -> list[str]:
    result = subprocess.run(
        ["ps", "-eo", "pid,cmd"], capture_output=True, text=True, timeout=30
    )
    return [
        line.strip()
        for line in result.stdout.splitlines()
        if "Hyprland" in line and "-c " in line and "smoke" in line
    ]


def assert_no_stale_sessions() -> None:
    """Refuse to start while a previous run left a compositor behind.

    An orphaned nested Hyprland keeps running with a deleted config and
    surfaces emergency-mode windows, so a stale run is a hard error rather
    than something to layer another session on top of.
    """
    stale = hyprland_processes()
    if stale:
        raise HarnessError(
            "a previous renderer smoke session is still running; kill it first: "
            + "; ".join(stale)
        )


def command_path(name: str) -> str:
    found = shutil.which(name)
    if found is None:
        raise HarnessError(f"required command not found: {name}")
    return found


def hyprctl_json(hyprctl: str, command: str, instance: str | None = None) -> list:
    args = [hyprctl, "--instance", instance, "-j", command] if instance else [hyprctl, "-j", command]
    result = subprocess.run(args, capture_output=True, text=True, timeout=30)
    if result.returncode != 0:
        raise HarnessError(f"hyprctl {command} failed: {result.stderr.strip()}")
    return json.loads(result.stdout or "[]")


def write_config(path: Path) -> None:
    # The bootstrap Wayland window monitor occupies 0x0; the test headless
    # output is staged to its right so the compositor does not complain about
    # an overlapping layout (which would paint over the wallpaper capture).
    path.write_text(
        "\n".join(
            [
                "-- Generated by the Realmheart renderer smoke harness.",
                'hl.monitor({ output = "", mode = "1280x720@60", position = "0x0", scale = 1 })',
                "hl.config({",
                "  animations = { enabled = false },",
                "  misc = {",
                "    disable_hyprland_logo = true,",
                "    disable_splash_rendering = true,",
                "    disable_watchdog_warning = true,",
                "    disable_xdg_env_checks = true,",
                "    disable_hyprland_guiutils_check = true,",
                "    force_default_wallpaper = 0,",
                "  },",
                "})",
                "",
            ]
        ),
        encoding="utf-8",
    )


class RendererProcess:
    """The real renderer, driven over its stdio protocol."""

    def __init__(self, executable: str, wayland_display: str) -> None:
        env = os.environ.copy()
        env["WAYLAND_DISPLAY"] = wayland_display
        env.pop("HYPRLAND_INSTANCE_SIGNATURE", None)
        self._process = subprocess.Popen(
            [executable, "--stdio"],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=env,
            text=True,
            bufsize=1,
        )
        # The renderer announces readiness after it has created its surfaces.
        ready = self._read_line(timeout=30.0)
        if ready != "READY":
            raise HarnessError(f"renderer never became ready: {ready!r}")

    def _read_line(self, timeout: float) -> str:
        assert self._process.stdout is not None
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            response = self._process.stdout.readline()
            if response:
                return response.strip()
            if self._process.poll() is not None:
                stderr = self._process.stderr.read() if self._process.stderr else ""
                raise HarnessError(
                    f"renderer exited with status {self._process.returncode}: {stderr}"
                )
        raise HarnessError("renderer did not answer in time")

    def command(self, line: str, timeout: float = 20.0) -> str:
        assert self._process.stdin is not None
        self._process.stdin.write(line + "\n")
        self._process.stdin.flush()
        # A COMMIT that starts a transition answers only once the final frame
        # is submitted, so allow a generous wait for that boundary.
        return self._read_line(timeout=timeout)

    def close(self) -> None:
        if self._process.poll() is None:
            try:
                self.command("QUIT", timeout=10.0)
            except HarnessError:
                self._process.kill()
        self._process.wait(timeout=10)


def encode_path(path: Path) -> str:
    return base64.b64encode(str(path).encode()).decode()


def wait_for_output(hyprctl: str, instance: str, timeout: float = 15.0) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        monitors = hyprctl_json(hyprctl, "monitors", instance=instance)
        if any(str(monitor.get("name")) == OUTPUT_NAME for monitor in monitors):
            return
        time.sleep(0.2)
    raise HarnessError(f"headless output {OUTPUT_NAME} never appeared")


def capture(hyprctl: str, instance: str, grim: str, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env["WAYLAND_DISPLAY"] = capture.socket  # type: ignore[attr-defined]
    env["HYPRLAND_INSTANCE_SIGNATURE"] = instance
    result = subprocess.run(
        [grim, "-o", OUTPUT_NAME, str(destination)],
        capture_output=True,
        text=True,
        timeout=120,
        env=env,
    )
    if result.returncode != 0:
        print(f"[capture] grim failed: {result.stderr.strip()}")
    deadline = time.monotonic() + 20
    while time.monotonic() < deadline:
        if destination.exists() and destination.stat().st_size > 0:
            return
        time.sleep(0.2)
    raise HarnessError(f"screenshot never appeared: {destination}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--renderer",
        default=str(REPO_ROOT / "build-verify" / "realmheart-wallpaper-renderer"),
    )
    parser.add_argument("--image", default=None, help="image used as a wallpaper")
    parser.add_argument("--keep", action="store_true", help="keep the isolated session")
    args = parser.parse_args()

    hyprctl = command_path("hyprctl")
    hyprland = command_path("Hyprland") if shutil.which("Hyprland") else command_path("hyprland")
    dbus_run_session = command_path("dbus-run-session")
    grim = command_path("grim")

    image = (
        Path(args.image)
        if args.image
        else REPO_ROOT / "assets" / "Showcase" / "Screenshots" / "WallpaperSwitcher.png"
    )
    if not image.is_file():
        raise HarnessError(f"wallpaper image not found: {image}")
    if not Path(args.renderer).is_file():
        raise HarnessError(f"renderer binary not found: {args.renderer}")
    assert_no_stale_sessions()

    session_root = Path(tempfile.mkdtemp(prefix="realmheart-renderer-smoke-", dir="/tmp"))
    output_dir = Path("/tmp/realmheart-display-tests") / "renderer-smoke"
    output_dir.mkdir(parents=True, exist_ok=True)

    config_path = session_root / "hyprland.lua"
    write_config(config_path)
    log_path = output_dir / "hyprland.log"

    existing = {
        str(item.get("instance"))
        for item in hyprctl_json(hyprctl, "instances")
        if isinstance(item, dict) and item.get("instance")
    }
    # The nested compositor creates its own Wayland socket next to the host
    # session's. Keep XDG_RUNTIME_DIR standard; Aquamarine refuses a
    # non-standard runtime directory, so the socket is found by difference.
    host_runtime = Path(os.environ.get("XDG_RUNTIME_DIR", "/tmp"))
    known_sockets = {path.name for path in host_runtime.glob("wayland-*")}

    env = os.environ.copy()
    env.pop("HYPRLAND_INSTANCE_SIGNATURE", None)
    env.pop("HYPRLAND_CMD", None)
    env.update(
        {
            "HYPRLAND_NO_SD_VARS": "1",
            "HYPRLAND_NO_SD_NOTIFY": "1",
            "HYPRLAND_NO_RT": "1",
            "XDG_CONFIG_HOME": str(session_root / "config"),
            "XDG_STATE_HOME": str(session_root / "state"),
            "XDG_CACHE_HOME": str(session_root / "cache"),
            "XDG_DATA_HOME": str(session_root / "data"),
        }
    )
    for subdir in ("config", "state", "cache", "data"):
        (session_root / subdir).mkdir(parents=True, exist_ok=True)

    # Track everything that must die before the temp dir can be removed. The
    # nested compositor is launched as its own process group leader, and it is
    # that group which is signalled: dbus-run-session does not forward a
    # termination to the compositor it spawned, so signalling the wrapper alone
    # orphans a Hyprland that later wakes with no config (emergency mode).
    tracked: dict[int, subprocess.Popen] = {}
    cleanup_done = False

    def terminate_tracked() -> None:
        for pid, process in list(tracked.items()):
            if process.poll() is None:
                try:
                    os.killpg(pid, signal.SIGTERM)
                except (ProcessLookupError, PermissionError):
                    pass
        deadline = time.monotonic() + 10
        while time.monotonic() < deadline:
            if all(process.poll() is not None for _, process in tracked.items()):
                break
            time.sleep(0.2)
        for pid, process in list(tracked.items()):
            if process.poll() is None:
                try:
                    os.killpg(pid, signal.SIGKILL)
                except (ProcessLookupError, PermissionError):
                    pass

    def cleanup(success: bool) -> None:
        nonlocal cleanup_done
        if cleanup_done:
            return
        cleanup_done = True
        terminate_tracked()
        survivors = hyprland_processes()
        if survivors:
            # Never delete the config of a compositor that is still alive; that
            # is what turns a leaked session into emergency-mode windows.
            print(
                "[session] WARNING: nested Hyprland survived cleanup: "
                + "; ".join(survivors),
                file=sys.stderr,
            )
        # Never leave a temp config behind for a surviving compositor to find.
        if not args.keep and not survivors:
            shutil.rmtree(session_root, ignore_errors=True)
        elif args.keep and success:
            print(f"[session] kept isolated session at {session_root}")

    import atexit

    atexit.register(cleanup, False)

    nested: subprocess.Popen | None = None
    renderer: RendererProcess | None = None
    try:
        with log_path.open("w", encoding="utf-8") as log_stream:
            nested = subprocess.Popen(
                [dbus_run_session, "--", hyprland, "-c", str(config_path)],
                stdout=log_stream,
                stderr=subprocess.STDOUT,
                env=env,
                start_new_session=True,
            )
            # The compositor is a child of the wrapper; its group leader is the
            # wrapper PID, and the compositor joins that group because
            # start_new_session=True applies to dbus-run-session and its
            # children.
            tracked[nested.pid] = nested
            instance = None
            deadline = time.monotonic() + 20
            while time.monotonic() < deadline:
                if nested.poll() is not None:
                    raise HarnessError(f"nested Hyprland exited with {nested.returncode}")
                instances = hyprctl_json(hyprctl, "instances")
                fresh = [
                    item
                    for item in instances
                    if isinstance(item, dict) and str(item.get("instance")) not in existing
                ]
                if fresh:
                    instance = str(max(fresh, key=lambda item: int(item.get("time", 0)))["instance"])
                    break
                time.sleep(0.2)
            if instance is None:
                raise HarnessError("nested Hyprland never reported an instance")

            for command in (
                ["output", "create", "headless", OUTPUT_NAME],
                # Staged right of the 1280-wide bootstrap monitor.
                ["monitor", OUTPUT_NAME + "," + OUTPUT_SIZE + ",1280x0,1"],
            ):
                subprocess.run(
                    [hyprctl, "--instance", instance, *command],
                    capture_output=True,
                    text=True,
                    timeout=30,
                )
            wait_for_output(hyprctl, instance)
            print(f"[session] instance={instance} output={OUTPUT_NAME}")

            deadline = time.monotonic() + 15
            fresh_sockets = []
            while time.monotonic() < deadline:
                fresh_sockets = [
                    path.name
                    for path in host_runtime.glob("wayland-*")
                    if path.name not in known_sockets and path.is_socket()
                ]
                if fresh_sockets:
                    break
                time.sleep(0.2)
            if not fresh_sockets:
                raise HarnessError("no new Wayland socket appeared for the nested session")
            wayland_display = sorted(fresh_sockets)[0]
            print(f"[session] wayland socket={wayland_display}")
            capture.socket = wayland_display  # type: ignore[attr-defined]

            renderer = RendererProcess(str(Path(args.renderer).resolve()), wayland_display)
            results: list[tuple[str, str]] = []

            def check(label: str, line: str, expected: str) -> None:
                response = renderer.command(line)
                results.append((label, response))
                if not response.startswith(expected):
                    raise HarnessError(f"{label}: expected {expected!r}, got {response!r}")
                print(f"[protocol] {label}: {response}")

            check("ping", "PING", "OK")
            # SET with no current wallpaper draws the first frame immediately.
            check("set-path", f"SET {encode_path(image)}", "OK")
            time.sleep(0.5)
            capture(hyprctl, instance, grim, output_dir / "renderer-set-static.png")

            # PREPARE must not disturb the visible wallpaper, COMMIT promotes it.
            check("prepare-path", f"PREPARE {encode_path(image)}", "PREPARED")
            check("commit-prepared", "COMMIT", "OK")
            time.sleep(0.8)
            capture(
                hyprctl, instance, grim, output_dir / "renderer-after-transition.png"
            )

            # Per-output override is independent of the global wallpaper.
            check(
                "prepare-output",
                f"PREPARE_OUTPUT {base64.b64encode(OUTPUT_NAME.encode()).decode()} "
                f"{encode_path(image)}",
                "PREPARED",
            )
            check("commit-output-override", "COMMIT", "OK")

            check("discard-noop", "DISCARD", "OK")
            check("prepare-then-discard", f"PREPARE {encode_path(image)}", "PREPARED")
            check("discard-prepared", "DISCARD", "OK")

            # A malformed command must fail closed without killing the renderer.
            response = renderer.command("SET !!!not-base64!!!")
            if not response.startswith("ERROR"):
                raise HarnessError(f"malformed path must be rejected, got {response!r}")
            print(f"[protocol] malformed-path: {response}")
            check("still-alive", "PING", "OK")

            renderer.close()
            renderer = None

        print(f"[capture] {output_dir}")
        print("[smoke] renderer protocol + static render path OK")
        # Ask the compositor to leave first so it can tear down its clients,
        # then let the group-level cleanup confirm it is really gone.
        subprocess.run(
            [hyprctl, "--instance", instance, "dispatch", "exit"],
            capture_output=True,
            text=True,
            timeout=30,
        )
        cleanup(True)
        return 0
    finally:
        # Covers every early exit: an error, a KeyboardInterrupt, or a crash.
        if renderer is not None:
            renderer.close()
        cleanup(False)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except HarnessError as error:
        print(f"[smoke] FAILED: {error}", file=sys.stderr)
        raise SystemExit(1)
